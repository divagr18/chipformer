"""Canonical token traces: encoding, parsing and replay.

A trace is::

    BOOT  <state dump writes>  STEP
    <record> STEP  <record> STEP  ...

where each record is one of
    instruction:  <writes>                     (generated by the model)
    timer tick:   TICK <DT write> <ST write>   (TICK injected by the host)
    input:        <KEY cell write>             (injected whole by the host)

and every write is the token pair ``ADDR a, VAL v``.
"""

from dataclasses import dataclass, field

from chipformer import spec
from chipformer.ref.emu import Chip8, Writes, apply_writes
from chipformer.spec import BOOT, STEP, TICK


def encode_writes(writes: Writes) -> list[int]:
    out = []
    for a, v in writes:
        out += [spec.addr_token(a), spec.val_token(v)]
    return out


def boot_tokens(cells: list[int]) -> list[int]:
    from chipformer.ref.emu import state_writes

    return [BOOT] + encode_writes(state_writes(cells)) + [STEP]


@dataclass
class Record:
    kind: str  # "boot" | "instr" | "tick"
    writes: Writes = field(default_factory=list)


def parse(tokens: list[int], allow_reboot: bool = False) -> list[Record]:
    """Split a trace into records, validating its grammar.

    ``allow_reboot`` accepts later BOOT records (context rollover in a dumped session).
    """
    records: list[Record] = []
    cur: Record | None = None
    i = 0
    while i < len(tokens):
        t = tokens[i]
        if t == STEP:
            if cur is None:
                raise ValueError(f"empty record before STEP at {i}")
            records.append(cur)
            cur = None
            i += 1
        elif t in (BOOT, TICK):
            if cur is not None:
                raise ValueError(f"{spec.token_name(t)} inside a record at {i}")
            if t == BOOT and records and not allow_reboot:
                raise ValueError(f"BOOT after start at {i}")
            cur = Record("boot" if t == BOOT else "tick")
            i += 1
        elif spec.is_addr(t):
            if i + 1 >= len(tokens) or not spec.is_val(tokens[i + 1]):
                raise ValueError(f"ADDR not followed by VAL at {i}")
            if cur is None:
                cur = Record("instr")
            cur.writes.append((t - spec.ADDR_BASE, tokens[i + 1] - spec.VAL_BASE))
            i += 2
        else:
            raise ValueError(f"unexpected token {spec.token_name(t)} at {i}")
    if cur is not None:
        raise ValueError("trace ends inside a record")
    if not records or records[0].kind != "boot":
        raise ValueError("trace must start with BOOT")
    return records


def replay(tokens: list[int]) -> list[int]:
    """Rebuild the machine state from a trace alone."""
    cells = [0] * spec.NUM_CELLS
    for r in parse(tokens):
        apply_writes(cells, r.writes)
    return cells


class Machine:
    """Drives the reference emulator and records the canonical trace.

    This is the ground truth the transformer must reproduce token for token.
    """

    def __init__(self, rom: bytes, quirks: "str | tuple[str, ...] | None" = None):
        self.emu = Chip8(rom, quirks)
        self.tokens = boot_tokens(self.emu.cells)
        self.generated = [False] * len(self.tokens)  # tokens the model must predict

    def _emit(self, tokens: list[int], generated: bool) -> None:
        self.tokens += tokens
        self.generated += [generated] * len(tokens)

    def step(self) -> Writes:
        w = self.emu.step()
        self._emit(encode_writes(w) + [STEP], True)
        return w

    def tick(self) -> Writes:
        w = self.emu.tick()
        self._emit([TICK], False)
        self._emit(encode_writes(w) + [STEP], True)
        return w

    def set_key(self, key: int, down: bool) -> None:
        if bool(self.emu.cells[spec.KEYS + key]) == down:
            return
        self._emit(encode_writes(self.emu.set_key(key, down)) + [STEP], False)
